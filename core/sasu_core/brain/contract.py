"""What the AI is told, as one JSON document: tool schemas, role tool sets, provider specs
and the system prompt. The Swift core embeds this (apps/mac/.../BrainContract.swift),
generated with `pnpm brain:gen`, so both cores give the AI exactly the same instructions.
"""

from __future__ import annotations

import json
from dataclasses import asdict

from ..security.roles import KID_TOOLS
from ..tools import GUEST_TOOLS, schemas
from .prompts import FUN, SYSTEM
from .providers import SPECS


def contract() -> dict[str, object]:
    return {
        "tools": schemas(),
        "guest_tools": sorted(GUEST_TOOLS),
        "kid_tools": sorted(KID_TOOLS),
        "providers": {k: asdict(v) for k, v in SPECS.items()},
        "system": SYSTEM,
        "fun": FUN,
    }


def swift_source() -> str:
    body = json.dumps(contract(), ensure_ascii=False, indent=1, sort_keys=True)
    return (
        "// GENERATED by `pnpm brain:gen` from core/sasu_core/brain/contract.py — do not edit.\n"
        "// The AI's tools, roles, providers and system prompt, shared with the Python core.\n"
        'let brainContractJSON = #"""\n' + body + '\n"""#\n'
    )


if __name__ == "__main__":
    print(swift_source(), end="")
